function check(name, cond, extra) { if (cond) { passes++; console.log(`  ✓ ${name}`); } else { failures++; console.log(`  ✗ ${name}${extra ? ' — ' + JSON.stringify(extra).slice(0, 300) : ''}`); } }
async function call(method, p, body, token) {
  const res = await fetch(BASE + p, { method, headers: { 'content-type': 'application/json', ...(token ? { authorization: 'Bearer ' + token } : {}) }, body: body ? JSON.stringify(body) : undefined });
  let data = null; const text = await res.text(); try { data = JSON.parse(text); } catch { data = text; }
  return { status: res.status, data };
}

